  @override
  Widget build(BuildContext context) {
    // Menerima passing argument[cite: 1]
    final mode = ModalRoute.of(context)!.settings.arguments as String;
    final provider = Provider.of<CurrencyProvider>(context, listen: false);
    
    final currencyList = provider.rates.keys.toList();

    return Scaffold(
      appBar: AppBar(
        title: Text('Pilih Mata Uang ($mode)'),
      ),
      body: ListView.builder(
        itemCount: currencyList.length,
        itemBuilder: (context, index) {
          String currencyCode = currencyList[index];
          
          // Memanggil nama negara. Jika API tiba-tiba menambah mata uang baru yang belum ada di daftar, pakai teks default
          String currencyName = currencyNames[currencyCode] ?? 'Mata Uang Internasional';

          return ListTile(
            leading: CircleAvatar(
              backgroundColor: Colors.blue.shade100,
              child: Text(currencyCode[0], style: const TextStyle(fontWeight: FontWeight.bold, color: Colors.blueAccent)),
            ),
            title: Text(currencyCode, style: const TextStyle(fontWeight: FontWeight.bold)),
            subtitle: Text(currencyName, style: TextStyle(color: Colors.grey.shade600)), 
            trailing: const Icon(Icons.arrow_forward_ios, size: 16),
            onTap: () {
              Navigator.pop(context, currencyCode);
            },
          );
        },
      ),
    );
  }
